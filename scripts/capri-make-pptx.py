INVALID_XML_RE = re.compile(r'[\x00-\x08\x0b\x0c\x0e-\x1f\ufffe\uffff]')


def clean_text(value) -> str:
    if value is None:
        return ''
    return INVALID_XML_RE.sub('', str(value))


