def build_slide_xml(title: str, bullets: list) -> str:
    safe_title = escape(clean_text(title))
    bullet_paras = []
    for b in bullets:
        safe_b = escape(clean_text(b))
        if not safe_b:
            continue
        bullet_paras.append(
            '<a:p>'
            '<a:pPr marL="285750" indent="-285750"><a:buChar char="&#x2022;"/></a:pPr>'
            f'<a:r><a:rPr lang="ru-RU" sz="2000"/><a:t>{safe_b}</a:t></a:r>'
            '</a:p>'
        )
    if not bullet_paras:
        bullet_paras.append('<a:p><a:endParaRPr lang="ru-RU" sz="2000"/></a:p>')

    return (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<p:sld xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" '
        'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" '
        'xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main">'
        '<p:cSld><p:spTree>'
        '<p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr>'
        '<p:grpSpPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="0" cy="0"/><a:chOff x="0" y="0"/><a:chExt cx="0" cy="0"/></a:xfrm></p:grpSpPr>'
        '<p:sp>'
        '<p:nvSpPr><p:cNvPr id="2" name="Title"/><p:cNvSpPr/><p:nvPr/></p:nvSpPr>'
        '<p:spPr><a:xfrm><a:off x="685800" y="457200"/><a:ext cx="10820400" cy="1143000"/></a:xfrm>'
        '<a:prstGeom prst="rect"><a:avLst/></a:prstGeom><a:noFill/></p:spPr>'
        '<p:txBody><a:bodyPr wrap="square"/><a:lstStyle/>'
        f'<a:p><a:r><a:rPr lang="ru-RU" sz="3200" b="1"/><a:t>{safe_title}</a:t></a:r></a:p>'
        '</p:txBody></p:sp>'
        '<p:sp>'
        '<p:nvSpPr><p:cNvPr id="3" name="Content"/><p:cNvSpPr/><p:nvPr/></p:nvSpPr>'
        '<p:spPr><a:xfrm><a:off x="685800" y="1752600"/><a:ext cx="10820400" cy="4572000"/></a:xfrm>'
        '<a:prstGeom prst="rect"><a:avLst/></a:prstGeom><a:noFill/></p:spPr>'
        '<p:txBody><a:bodyPr wrap="square"/><a:lstStyle/>'
        + ''.join(bullet_paras) +
        '</p:txBody></p:sp>'
        '</p:spTree></p:cSld>'
        '<p:clrMapOvr><a:masterClrMapping/></p:clrMapOvr>'
        '</p:sld>'
    )


def make_pptx(out_path: str, slides: list, default_title: str = 'Презентация') -> None:
    if not slides:
        slides = [{'title': default_title, 'bullets': []}]

    n = len(slides)
    overrides = [
        '<Override PartName="/ppt/presentation.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.presentation.main+xml"/>',
        '<Override PartName="/ppt/slideMasters/slideMaster1.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.slideMaster+xml"/>',
        '<Override PartName="/ppt/slideLayouts/slideLayout1.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.slideLayout+xml"/>',
        '<Override PartName="/ppt/theme/theme1.xml" ContentType="application/vnd.openxmlformats-officedocument.theme+xml"/>',
    ]
    pres_rels = [
        '<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/slideMaster" Target="slideMasters/slideMaster1.xml"/>',
    ]
    slide_id_list = []

    for i in range(1, n + 1):
        overrides.append(
            f'<Override PartName="/ppt/slides/slide{i}.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.slide+xml"/>'
        )
        rid = f'rId{i + 1}'
        pres_rels.append(
            f'<Relationship Id="{rid}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/slide" Target="slides/slide{i}.xml"/>'
        )
        slide_id_list.append(f'<p:sldId id="{255 + i}" r:id="{rid}"/>')

    content_types_xml = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
        '<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
        '<Default Extension="xml" ContentType="application/xml"/>'
        + ''.join(overrides) +
        '</Types>'
    )

    pres_rels_xml = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
        + ''.join(pres_rels) +
        '</Relationships>'
    )

    presentation_xml = (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
        '<p:presentation xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main" '
        'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships" '
        'xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main">'
        '<p:sldMasterIdLst><p:sldMasterId id="2147483648" r:id="rId1"/></p:sldMasterIdLst>'
        f'<p:sldIdLst>{"".join(slide_id_list)}</p:sldIdLst>'
        '<p:sldSz cx="12192000" cy="6858000"/>'
        '<p:notesSz cx="6858000" cy="9144000"/>'
        '</p:presentation>'
    )

    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with zipfile.ZipFile(out_path, 'w', compression=zipfile.ZIP_DEFLATED) as zf:
        zf.writestr('[Content_Types].xml', content_types_xml)
        zf.writestr('_rels/.rels', ROOT_RELS_XML)
        zf.writestr('ppt/presentation.xml', presentation_xml)
        zf.writestr('ppt/_rels/presentation.xml.rels', pres_rels_xml)
        zf.writestr('ppt/slideMasters/slideMaster1.xml', SLIDE_MASTER_XML)
        zf.writestr('ppt/slideMasters/_rels/slideMaster1.xml.rels', SLIDE_MASTER_RELS_XML)
        zf.writestr('ppt/slideLayouts/slideLayout1.xml', SLIDE_LAYOUT_XML)
        zf.writestr('ppt/slideLayouts/_rels/slideLayout1.xml.rels', SLIDE_LAYOUT_RELS_XML)
        zf.writestr('ppt/theme/theme1.xml', THEME_XML)
        for i, slide in enumerate(slides, start=1):
            if not isinstance(slide, dict):
                slide = {'title': str(slide), 'bullets': []}
            s_title = slide.get('title') or f'Слайд {i}'
            s_bullets = slide.get('bullets') or []
            if isinstance(s_bullets, str):
                s_bullets = [s_bullets]
            zf.writestr(f'ppt/slides/slide{i}.xml', build_slide_xml(s_title, s_bullets))
            zf.writestr(f'ppt/slides/_rels/slide{i}.xml.rels', SLIDE_RELS_XML)


def main() -> int:
    parser = argparse.ArgumentParser(description='Generate PPTX from JSON slides')
    parser.add_argument('--input', required=True, help='Path to JSON input file')
    parser.add_argument('--out', required=True, help='Output .pptx file path')
    args = parser.parse_args()

    with open(args.input, 'r', encoding='utf-8') as f:
        payload = json.load(f)

    if isinstance(payload, list):
        slides = payload
        title = 'Презентация'
    elif isinstance(payload, dict):
        slides = payload.get('slides') or []
        title = payload.get('title') or 'Презентация'
    else:
        raise ValueError('Invalid JSON payload')

    make_pptx(args.out, slides, title)
    print(json.dumps({'ok': True, 'path': os.path.abspath(args.out), 'slides': len(slides) or 1}, ensure_ascii=False))
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except Exception as exc:
        print(json.dumps({'ok': False, 'error': str(exc)}, ensure_ascii=False))
        sys.exit(1)
